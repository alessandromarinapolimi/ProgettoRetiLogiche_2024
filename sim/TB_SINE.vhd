        );

    -- First rising edge at 14 ns.
    CLK_PROC : process
    begin
        CLK <= '1';
        wait for CLK_PERIOD/2;
        CLK <= '0';
        wait for CLK_PERIOD/2;
    end process CLK_PROC;

    RESET_PROC : process
    begin
        RESET <= '1';
        wait for CLK_PERIOD*2;
        RESET <= '0';
        wait;
    end process RESET_PROC;

    -- ANGLE changes on a falling edge and the registered result is checked
    -- one period later, on the next falling edge.
    STIM_PROC : process
        variable ERRORS : natural := 0;
    begin
        wait for CLK_PERIOD + CLK_PERIOD/2;
        if SINE /= "0000000000" then
            ERRORS := ERRORS + 1;
            report "Reset: expected 0000000000, got " & to_string(SINE) severity error;
        end if;
        wait for CLK_PERIOD*6;

        for i in 0 to 359 loop
            ANGLE <= std_logic_vector(to_unsigned(i, ANGLE'length));
            wait for CLK_PERIOD;
            if SINE /= EXPECTED_SINE(i) then
                ERRORS := ERRORS + 1;
                report "Angle " & integer'image(i) & ": expected "
                       & to_string(EXPECTED_SINE(i)) & ", got " & to_string(SINE)
                    severity error;
            end if;
        end loop;

        if ERRORS = 0 then
            report "TB_SINE: reset and all 360 angles match" severity note;
        else
            report "TB_SINE: " & integer'image(ERRORS) & " mismatches" severity failure;
        end if;

        std.env.finish;
    end process STIM_PROC;

